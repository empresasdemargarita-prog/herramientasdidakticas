// ── FUNCIÓN DE BÚSQUEDA ────────────────────────────────────────────────
function buscarProductos(termino) {
  if (!termino || termino.trim() === "") return [];
  const t = termino.toLowerCase().trim();
  return productos.filter(p => {
    const enNombre = p.nombre.toLowerCase().includes(t);
    const enDesc = p.descripcion.toLowerCase().includes(t);
    const enCat = p.categoriaNombre.toLowerCase().includes(t);
    const enCaract = p.caracteristicas.some(c => c.toLowerCase().includes(t));
    return enNombre || enDesc || enCat || enCaract;
  });
}

// ── FUNCIÓN PARA OBTENER PRODUCTOS POR CATEGORÍA ──────────────────────
function productosPorCategoria(cat) {
  return productos.filter(p => {
    if (Array.isArray(p.categoria)) return p.categoria.includes(cat);
    return p.categoria === cat;
  });
}
